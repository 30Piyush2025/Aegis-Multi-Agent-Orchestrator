    def execute_task(
        self,
        task_spec: Union[Task, Dict[str, Any]],
        state: Optional[Any] = None,
    ) -> WorkerResult:
        """
        Execute backend engineering task: generate API, schemas, and controllers,
        validate code syntax and security gates, and persist artifacts.
        """
        start_time = time.perf_counter()

        # Extract task metadata
        if hasattr(task_spec, "id"):
            task_id = task_spec.id
            title = task_spec.title
            desc = task_spec.description
            inputs = getattr(task_spec, "inputs", {})
        else:
            task_id = task_spec.get("id", f"TASK-{int(time.time())}")
            title = task_spec.get("title", "Backend API Development")
            desc = task_spec.get("description", "Generate REST API and business logic")
            inputs = task_spec.get("inputs", {})

        self.log(f"Starting task execution: {task_id} - '{title}'")
        self._sync_start(task_id, state)

        # 1. Research specifications if necessary
        research = self.web_researcher.search("fastapi rest api pydantic models")

        # 2. Extract entities and framework preference
        framework = inputs.get("framework", "fastapi")
        entities = inputs.get("entities", ["ServiceRecord", "TaskItem"])

        # 3. Generate Backend Code
        code = self._generate_api_code(
            title=title,
            description=desc,
            framework=framework,
            entities=entities,
        )

        # 4. Static Code Quality & Security Gate Check
        passed_gate, ast_res = self.validate_code(code)

        # If AST failed, attempt internal self-healing
        if not passed_gate or not ast_res.is_valid_syntax:
            self.log(f"Initial AST scan failed (score: {ast_res.quality_score}). Triggering auto-remediation...", level="WARNING")
            remediation = self.heal(
                task_spec,
                error_context={"error": ast_res.syntax_error or "Quality gate violation", "code": code},
                state=state,
            )
            return remediation

        # 5. Persist Artifacts
        filename = f"backend_api_{task_id.replace('-', '_').lower()}.py"
        file_path = self.save_artifact(filename=filename, content=code, subdir="backend")

        # 6. Run Sandbox Self-Test
        exec_res = self.code_runner.run_code(code, timeout=10)

        elapsed = time.perf_counter() - start_time
        status = "SUCCESS" if exec_res.success else "FAILED"
        errors = [exec_res.stderr] if not exec_res.success else []

        result = WorkerResult(
            worker_name=self.name,
            task_id=task_id,
            status=status,
            output_code=code,
            file_path=file_path,
            stdout=exec_res.stdout,
            stderr=exec_res.stderr,
            execution_time=elapsed,
            errors=errors,
            quality_score=ast_res.quality_score,
            ast_metrics=ast_res.to_dict(),
            artifacts=[file_path],
            metadata={
                "framework": framework,
                "endpoints_count": len(ast_res.functions),
                "classes_count": ast_res.num_classes,
                "research_source": research.source,
            },
        )

        self._sync_finish(task_id, result, state)
        self.log(f"Task completed with status: {status} in {elapsed:.3f}s")
        return result

    def heal(
        self,
        task_spec: Union[Task, Dict[str, Any]],
        error_context: Dict[str, Any],
        state: Optional[Any] = None,
    ) -> WorkerResult:
        """
        Remediate syntax errors, dependency missing imports, or failed assertions.
        """
        self.status = WorkerStatus.HEALING
        error_msg = error_context.get("error", "")
        self.log(f"Self-healing triggered: {error_msg}")

        # Extract title and id
        task_id = getattr(task_spec, "id", None) or task_spec.get("id", "HEAL-TASK")
        title = getattr(task_spec, "title", None) or task_spec.get("title", "Healed Backend API")
        desc = getattr(task_spec, "description", None) or task_spec.get("description", "Remediated API service")

        # Regenerate clean baseline code
        clean_code = self._generate_api_code(
            title=f"{title} (Healed)",
            description=f"Auto-healed resolution for: {error_msg[:100]}",
            framework="fastapi",
        )

        # Validate remediation
        passed_gate, ast_res = self.validate_code(clean_code)
        filename = f"healed_backend_{task_id.replace('-', '_').lower()}.py"
        file_path = self.save_artifact(filename=filename, content=clean_code, subdir="backend")

        # Test runner
        exec_res = self.code_runner.run_code(clean_code, timeout=10)

        result = WorkerResult(
            worker_name=self.name,
            task_id=task_id,
            status="SUCCESS" if (passed_gate and exec_res.success) else "FAILED",
            output_code=clean_code,
            file_path=file_path,
            stdout=exec_res.stdout,
            stderr=exec_res.stderr,
            execution_time=0.5,
            errors=[exec_res.stderr] if not exec_res.success else [],
            quality_score=ast_res.quality_score,
            ast_metrics=ast_res.to_dict(),
            artifacts=[file_path],
            metadata={"healing_cycle": True, "remediated_error": error_msg},
        )
        self._sync_finish(task_id, result, state)
        return result
