    def execute_task(
        self,
        task_spec: Union[Task, Dict[str, Any]],
        state: Optional[Any] = None,
    ) -> WorkerResult:
        """
        Execute database engineering task: generate SQLite repository, schema migrations,
        run static AST scan, and execute in-memory test transaction in sandbox.
        """
        start_time = time.perf_counter()

        if hasattr(task_spec, "id"):
            task_id = task_spec.id
            title = task_spec.title
            desc = task_spec.description
            inputs = getattr(task_spec, "inputs", {})
        else:
            task_id = task_spec.get("id", f"TASK-{int(time.time())}")
            title = task_spec.get("title", "Database Layer Development")
            desc = task_spec.get("description", "Generate SQL schemas and ORM repository")
            inputs = task_spec.get("inputs", {})

        self.log(f"Starting database task: {task_id} - '{title}'")
        self._sync_start(task_id, state)

        # 1. Research specifications
        research = self.web_researcher.search("sqlite database schema orm repository")

        # 2. Generate Database Code
        tables = inputs.get("tables", ["records", "audit_logs"])
        code = self._generate_database_module(
            title=title,
            description=desc,
            tables=tables,
        )

        # 3. Static AST Validation
        passed_gate, ast_res = self.validate_code(code)
        if not passed_gate or not ast_res.is_valid_syntax:
            self.log("AST verification flagged issues in database code. Entering healing...", level="WARNING")
            return self.heal(
                task_spec,
                error_context={"error": ast_res.syntax_error or "DB code quality gate failed"},
                state=state,
            )

        # 4. Save Artifact
        filename = f"db_schema_{task_id.replace('-', '_').lower()}.py"
        file_path = self.save_artifact(filename=filename, content=code, subdir="database")

        # 5. Execute in Sandbox (Dry-run in-memory SQLite transactions)
        exec_res = self.code_runner.run_code(code, timeout=10)

        elapsed = time.perf_counter() - start_time
        status = "SUCCESS" if exec_res.success else "FAILED"
        errors = [exec_res.stderr] if not exec_res.success else []

        result = WorkerResult(
            worker_name=self.name,
            task_id=task_id,
            status=status,
            output_code=code,
            file_path=file_path,
            stdout=exec_res.stdout,
            stderr=exec_res.stderr,
            execution_time=elapsed,
            errors=errors,
            quality_score=ast_res.quality_score,
            ast_metrics=ast_res.to_dict(),
            artifacts=[file_path],
            metadata={
                "database_type": "sqlite",
                "tables": tables,
                "classes_count": ast_res.num_classes,
                "functions_count": len(ast_res.functions),
            },
        )

        self._sync_finish(task_id, result, state)
        self.log(f"Database task resolved: {status} in {elapsed:.3f}s")
        return result

    def heal(
        self,
        task_spec: Union[Task, Dict[str, Any]],
        error_context: Dict[str, Any],
        state: Optional[Any] = None,
    ) -> WorkerResult:
        """Remediate database schema conflicts or syntax errors."""
        self.status = WorkerStatus.HEALING
        error_msg = error_context.get("error", "Database syntax or migration error")
        self.log(f"Remediating database code: {error_msg}")

        task_id = getattr(task_spec, "id", None) or task_spec.get("id", "HEAL-DB")
        title = getattr(task_spec, "title", None) or task_spec.get("title", "Healed Database Schema")
        desc = getattr(task_spec, "description", None) or task_spec.get("description", "Remediated SQLite Repository")

        code = self._generate_database_module(
            title=f"{title} (Healed)",
            description=f"Auto-healed for error: {error_msg[:80]}",
        )

        passed_gate, ast_res = self.validate_code(code)
        filename = f"healed_db_{task_id.replace('-', '_').lower()}.py"
        file_path = self.save_artifact(filename=filename, content=code, subdir="database")

        exec_res = self.code_runner.run_code(code, timeout=10)

        result = WorkerResult(
            worker_name=self.name,
            task_id=task_id,
            status="SUCCESS" if (passed_gate and exec_res.success) else "FAILED",
            output_code=code,
            file_path=file_path,
            stdout=exec_res.stdout,
            stderr=exec_res.stderr,
            execution_time=0.4,
            errors=[exec_res.stderr] if not exec_res.success else [],
            quality_score=ast_res.quality_score,
            ast_metrics=ast_res.to_dict(),
            artifacts=[file_path],
            metadata={"healing_cycle": True, "remediated_error": error_msg},
        )
        self._sync_finish(task_id, result, state)
        return result
