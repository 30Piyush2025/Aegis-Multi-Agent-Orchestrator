class DatabaseManager:
    """Thread-safe SQLite database manager providing schema migration and CRUD operations."""

    def __init__(self, db_path: str = ":memory:") -> None:
        self.db_path = db_path
        self._conn: Optional[sqlite3.Connection] = None
        if self.db_path == ":memory:":
            self._conn = sqlite3.connect(":memory:")
            self._conn.row_factory = sqlite3.Row
            self._conn.execute("PRAGMA foreign_keys = ON;")
        self._init_tables()

    def get_connection(self) -> sqlite3.Connection:
        """Create or retrieve a configured SQLite database connection with row factory."""
        if self._conn is not None:
            return self._conn
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON;")
        return conn

    def _init_tables(self) -> None:
        """Execute DDL migrations to create schema and index structures."""
        with self.get_connection() as conn:
            cursor = conn.cursor()

            # Primary Table
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS {table_clean} (
                    id TEXT PRIMARY KEY,
                    title TEXT NOT NULL,
                    category TEXT DEFAULT 'general',
                    payload TEXT,
                    is_active INTEGER DEFAULT 1,
                    created_at REAL NOT NULL,
                    updated_at REAL NOT NULL
                );
            """)

            # Audit Log Table
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS audit_logs (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    entity_id TEXT NOT NULL,
                    action TEXT NOT NULL,
                    actor TEXT NOT NULL,
                    timestamp REAL NOT NULL,
                    FOREIGN KEY (entity_id) REFERENCES {table_clean}(id) ON DELETE CASCADE
                );
            """)

            # Indices for performance
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_{table_clean}_category
                ON {table_clean}(category);
            """)
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_{table_clean}_created
                ON {table_clean}(created_at);
            """)

            conn.commit()

