    def execute_task(
        self,
        task_spec: Union[Task, Dict[str, Any]],
        state: Optional[Any] = None,
    ) -> WorkerResult:
        """
        Execute frontend UI development task: generate Streamlit dashboard code,
        validate Python syntax with ASTScanner, verify execution, and persist artifact.
        """
        start_time = time.perf_counter()

        if hasattr(task_spec, "id"):
            task_id = task_spec.id
            title = task_spec.title
            desc = task_spec.description
            inputs = getattr(task_spec, "inputs", {})
        else:
            task_id = task_spec.get("id", f"TASK-{int(time.time())}")
            title = task_spec.get("title", "Frontend Dashboard Development")
            desc = task_spec.get("description", "Generate Streamlit Mission Control UI")
            inputs = task_spec.get("inputs", {})

        self.log(f"Starting frontend task: {task_id} - '{title}'")
        self._sync_start(task_id, state)

        # 1. Research UI recommendations
        research = self.web_researcher.search("streamlit mission control dashboard metrics tabs")

        # 2. Generate UI Code
        features = inputs.get("features", ["Overview", "Workers", "Artifacts", "Health"])
        code = self._generate_streamlit_app(
            title=title,
            description=desc,
            features=features,
        )

        # 3. Static AST Check
        passed_gate, ast_res = self.validate_code(code)

        if not passed_gate or not ast_res.is_valid_syntax:
            self.log("AST verification flagged issues. Entering auto-healing...", level="WARNING")
            return self.heal(
                task_spec,
                error_context={"error": ast_res.syntax_error or "Frontend AST score below threshold"},
                state=state,
            )

        # 4. Save Artifact
        filename = f"frontend_ui_{task_id.replace('-', '_').lower()}.py"
        file_path = self.save_artifact(filename=filename, content=code, subdir="frontend")

        # 5. Execute in Sandbox
        exec_res = self.code_runner.run_code(code, timeout=10)

        elapsed = time.perf_counter() - start_time
        status = "SUCCESS" if exec_res.success else "FAILED"
        errors = [exec_res.stderr] if not exec_res.success else []

        result = WorkerResult(
            worker_name=self.name,
            task_id=task_id,
            status=status,
            output_code=code,
            file_path=file_path,
            stdout=exec_res.stdout,
            stderr=exec_res.stderr,
            execution_time=elapsed,
            errors=errors,
            quality_score=ast_res.quality_score,
            ast_metrics=ast_res.to_dict(),
            artifacts=[file_path],
            metadata={
                "ui_framework": "streamlit",
                "functions_count": len(ast_res.functions),
                "features": features,
            },
        )

        self._sync_finish(task_id, result, state)
        self.log(f"Frontend task resolved: {status} in {elapsed:.3f}s")
        return result

    def heal(
        self,
        task_spec: Union[Task, Dict[str, Any]],
        error_context: Dict[str, Any],
        state: Optional[Any] = None,
    ) -> WorkerResult:
        """Heal frontend UI code issues."""
        self.status = WorkerStatus.HEALING
        error_msg = error_context.get("error", "Unknown UI glitch")
        self.log(f"Remediating frontend UI code: {error_msg}")

        task_id = getattr(task_spec, "id", None) or task_spec.get("id", "HEAL-UI")
        title = getattr(task_spec, "title", None) or task_spec.get("title", "Healed Dashboard")
        desc = getattr(task_spec, "description", None) or task_spec.get("description", "Remediated Streamlit App")

        code = self._generate_streamlit_app(
            title=f"{title} (Healed)",
            description=f"Auto-healed for: {error_msg[:80]}",
        )

        passed_gate, ast_res = self.validate_code(code)
        filename = f"healed_frontend_{task_id.replace('-', '_').lower()}.py"
        file_path = self.save_artifact(filename=filename, content=code, subdir="frontend")

        exec_res = self.code_runner.run_code(code, timeout=10)

        result = WorkerResult(
            worker_name=self.name,
            task_id=task_id,
            status="SUCCESS" if (passed_gate and exec_res.success) else "FAILED",
            output_code=code,
            file_path=file_path,
            stdout=exec_res.stdout,
            stderr=exec_res.stderr,
            execution_time=0.4,
            errors=[exec_res.stderr] if not exec_res.success else [],
            quality_score=ast_res.quality_score,
            ast_metrics=ast_res.to_dict(),
            artifacts=[file_path],
            metadata={"healing_cycle": True, "remediated_error": error_msg},
        )
        self._sync_finish(task_id, result, state)
        return result
