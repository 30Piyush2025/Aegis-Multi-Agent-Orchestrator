    def validate_typescript_code(self, code: str) -> Tuple[bool, Dict[str, Any]]:
        """
        Structural verification for Next.js / TypeScript code:
        Validates bracket balance, essential exports, and core JSX structure.
        """
        metrics: Dict[str, Any] = {
            "syntax_valid": True,
            "has_export": False,
            "has_react": False,
            "has_floating_windows": False,
            "errors": [],
            "quality_score": 100.0,
        }

        # Check bracket parity
        stack = []
        pairs = {')': '(', '}': '{', ']': '['}
        lines = code.split("\n")
        for line_num, line in enumerate(lines, 1):
            clean_line = re.sub(r'//.*$', '', line)
            for char in clean_line:
                if char in "({[":
                    stack.append((char, line_num))
                elif char in ")}]":
                    if not stack:
                        metrics["syntax_valid"] = False
                        metrics["errors"].append(f"Unmatched closing '{char}' at line {line_num}")
                        break
                    last_open, open_line = stack.pop()
                    if pairs[char] != last_open:
                        metrics["syntax_valid"] = False
                        metrics["errors"].append(f"Mismatched '{last_open}' (line {open_line}) and '{char}' (line {line_num})")
                        break

        if stack and metrics["syntax_valid"]:
            last_open, open_line = stack[-1]
            metrics["syntax_valid"] = False
            metrics["errors"].append(f"Unclosed '{last_open}' opened at line {open_line}")

        # Check critical Next.js / React idioms
        if "export default" in code or "export function" in code or "export const" in code:
            metrics["has_export"] = True
        else:
            metrics["quality_score"] -= 15.0
            metrics["errors"].append("Missing top-level export statement")

        if "react" in code.lower() or "use client" in code.lower():
            metrics["has_react"] = True

        if "floating" in code.lower() or "window" in code.lower():
            metrics["has_floating_windows"] = True

        if not metrics["syntax_valid"]:
            metrics["quality_score"] = 0.0

        return metrics["syntax_valid"], metrics

    def execute_task(
        self,
        task_spec: Union[Task, Dict[str, Any]],
        state: Optional[Any] = None,
    ) -> WorkerResult:
        """
        Execute frontend UI development task.
        Supports both modern Next.js desktop assistant applications (default)
        and legacy Streamlit dashboards based on `framework` input.
        """
        start_time = time.perf_counter()

        if hasattr(task_spec, "id"):
            task_id = task_spec.id
            title = task_spec.title
            desc = task_spec.description
            inputs = getattr(task_spec, "inputs", {})
        else:
            task_id = task_spec.get("id", f"TASK-{int(time.time())}")
            title = task_spec.get("title", "Frontend Desktop Assistant")
            desc = task_spec.get("description", "Generate Next.js AI Assistant with Floating Windows")
            inputs = task_spec.get("inputs", {})

        # Default to modern Next.js desktop assistant unless streamlit is explicitly requested
        framework = str(inputs.get("framework", "nextjs")).lower().strip()
        self.log(f"Starting frontend task: {task_id} - '{title}' [Framework: {framework}]")
        self._sync_start(task_id, state)

        # 1. Next.js Desktop Assistant Pathway (Primary)
        if framework in ["nextjs", "react", "next", "desktop"]:
            features = inputs.get(
                "features",
                ["Floating Windows", "Chat Assistant", "Calculator", "Clock", "Spreadsheet", "Art Studio"],
            )
            code = self._generate_nextjs_desktop_agent(
                title=title,
                description=desc,
                features=features,
            )

            is_valid, ts_metrics = self.validate_typescript_code(code)
            if not is_valid:
                self.log(f"TypeScript validation error: {ts_metrics['errors']}. Triggering heal...", level="WARNING")
                return self.heal(
                    task_spec,
                    error_context={"error": "; ".join(ts_metrics["errors"]), "framework": "nextjs"},
                    state=state,
                )

            filename = f"desktop_agent_{task_id.replace('-', '_').lower()}.tsx"
            file_path = self.save_artifact(filename=filename, content=code, subdir="frontend")

            elapsed = time.perf_counter() - start_time
            result = WorkerResult(
                worker_name=self.name,
                task_id=task_id,
                status="SUCCESS",
                output_code=code,
                file_path=file_path,
                stdout=f"Next.js App Router component generated with {len(features)} interactive tools and Floating Windows.",
                stderr="",
                execution_time=elapsed,
                errors=[],
                quality_score=ts_metrics["quality_score"],
                ast_metrics=ts_metrics,
                artifacts=[file_path],
                metadata={
                    "ui_framework": "nextjs",
                    "desktop_floating_windows": True,
                    "features": features,
                    "language": "typescript",
                },
            )
            self._sync_finish(task_id, result, state)
            self.log(f"Next.js desktop UI task completed: SUCCESS in {elapsed:.3f}s")
            return result

        # 2. Legacy Streamlit Dashboard Pathway (Backwards Compatible)
        features = inputs.get("features", ["Overview", "Workers", "Artifacts", "Health"])
        code = self._generate_streamlit_app(
            title=title,
            description=desc,
            features=features,
        )

        passed_gate, ast_res = self.validate_code(code)
        if not passed_gate or not ast_res.is_valid_syntax:
            self.log("AST verification flagged issues. Entering auto-healing...", level="WARNING")
            return self.heal(
                task_spec,
                error_context={"error": ast_res.syntax_error or "Frontend AST score below threshold", "framework": "streamlit"},
                state=state,
            )

        filename = f"frontend_ui_{task_id.replace('-', '_').lower()}.py"
        file_path = self.save_artifact(filename=filename, content=code, subdir="frontend")
        exec_res = self.code_runner.run_code(code, timeout=10)

        elapsed = time.perf_counter() - start_time
        status = "SUCCESS" if exec_res.success else "FAILED"
        errors = [exec_res.stderr] if not exec_res.success else []

        result = WorkerResult(
            worker_name=self.name,
            task_id=task_id,
            status=status,
            output_code=code,
            file_path=file_path,
            stdout=exec_res.stdout,
            stderr=exec_res.stderr,
            execution_time=elapsed,
            errors=errors,
            quality_score=ast_res.quality_score,
            ast_metrics=ast_res.to_dict(),
            artifacts=[file_path],
            metadata={
                "ui_framework": "streamlit",
                "functions_count": len(ast_res.functions),
                "features": features,
            },
        )

        self._sync_finish(task_id, result, state)
        self.log(f"Streamlit frontend task resolved: {status} in {elapsed:.3f}s")
        return result

    def heal(
        self,
        task_spec: Union[Task, Dict[str, Any]],
        error_context: Dict[str, Any],
        state: Optional[Any] = None,
    ) -> WorkerResult:
        """Heal frontend UI code issues across Next.js and Streamlit."""
        self.status = WorkerStatus.HEALING
        error_msg = error_context.get("error", "Unknown UI glitch")
        framework = error_context.get("framework", "nextjs")
        self.log(f"Remediating frontend UI code ({framework}): {error_msg}")

        task_id = getattr(task_spec, "id", None) or task_spec.get("id", "HEAL-UI")
        title = getattr(task_spec, "title", None) or task_spec.get("title", "Healed Interface")
        desc = getattr(task_spec, "description", None) or task_spec.get("description", "Remediated Application")

        if framework in ["nextjs", "react", "desktop"]:
            code = self._generate_nextjs_desktop_agent(
                title=f"{title} (Healed)",
                description=f"Auto-healed for: {error_msg[:80]}",
            )
            is_valid, ts_metrics = self.validate_typescript_code(code)
            filename = f"healed_desktop_agent_{task_id.replace('-', '_').lower()}.tsx"
            file_path = self.save_artifact(filename=filename, content=code, subdir="frontend")

            result = WorkerResult(
                worker_name=self.name,
                task_id=task_id,
                status="SUCCESS" if is_valid else "FAILED",
                output_code=code,
                file_path=file_path,
                stdout="Successfully healed Next.js desktop assistant component.",
                stderr="",
                execution_time=0.3,
                errors=ts_metrics.get("errors", []),
                quality_score=ts_metrics["quality_score"],
                ast_metrics=ts_metrics,
                artifacts=[file_path],
                metadata={"healing_cycle": True, "remediated_error": error_msg, "ui_framework": "nextjs"},
            )
            self._sync_finish(task_id, result, state)
            return result

        # Streamlit Healing
        code = self._generate_streamlit_app(
            title=f"{title} (Healed)",
            description=f"Auto-healed for: {error_msg[:80]}",
        )
        passed_gate, ast_res = self.validate_code(code)
        filename = f"healed_frontend_{task_id.replace('-', '_').lower()}.py"
        file_path = self.save_artifact(filename=filename, content=code, subdir="frontend")
        exec_res = self.code_runner.run_code(code, timeout=10)

        result = WorkerResult(
            worker_name=self.name,
            task_id=task_id,
            status="SUCCESS" if (passed_gate and exec_res.success) else "FAILED",
            output_code=code,
            file_path=file_path,
            stdout=exec_res.stdout,
            stderr=exec_res.stderr,
            execution_time=0.4,
            errors=[exec_res.stderr] if not exec_res.success else [],
            quality_score=ast_res.quality_score,
            ast_metrics=ast_res.to_dict(),
            artifacts=[file_path],
            metadata={"healing_cycle": True, "remediated_error": error_msg, "ui_framework": "streamlit"},
        )
        self._sync_finish(task_id, result, state)
        return result
